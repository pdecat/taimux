//! SHA-256, because Gemini names a project directory after one.
//!
//! Gemini CLI keeps a session under `~/.gemini/tmp/<name>/chats/`, where `<name>`
//! is either a friendly label or the SHA-256 of the absolute working directory,
//! depending on which version wrote it. Half the directories here are each kind.
//! Without the hash, half of those sessions can only show `?` where their
//! directory goes, and the directory is a column you read every row by.
//!
//! Eighty lines of FIPS 180-4 rather than a crate: this is the only hash in the
//! project, it will never need another algorithm, and the `sqlite` feature is
//! already the one dependency `core` takes. The known-answer tests below are the
//! whole argument that it is right.

